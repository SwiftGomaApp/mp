export const CLIENT_ERROR_CODES = {
  NETWORK_ERROR: "NETWORK_ERROR",
  TIMEOUT: "TIMEOUT",
  NOT_AUTHENTICATED: "NOT_AUTHENTICATED",
  UNKNOWN_ERROR: "UNKNOWN_ERROR",
} as const;

export type ServerErrorCode = keyof typeof ERROR_CODES;
export type ClientErrorCode = keyof typeof CLIENT_ERROR_CODES;
export type KnownErrorCode = ServerErrorCode | ClientErrorCode;
export type ErrorCode = KnownErrorCode | (string & {});

const has = (object: object, key: string): boolean =>
  Object.prototype.hasOwnProperty.call(object, key);

export function isKnownErrorCode(code: unknown): code is KnownErrorCode {
  return typeof code === "string" && (has(ERROR_CODES, code) || has(CLIENT_ERROR_CODES, code));
}
